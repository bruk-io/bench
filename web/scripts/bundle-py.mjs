// Bundle the Python side into a generated TS module: the worker writes PY_SOURCES
// into Pyodide's filesystem, the Examples menu loads EXAMPLES, and a new file starts as STARTER.
import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const WEB = dirname(HERE);
const ROOT = dirname(WEB);
const PY_ROOT = join(ROOT, "src");
const EXAMPLES = join(ROOT, "examples");
const STARTER = join(ROOT, "templates", "untitled.py");
const OUT = join(WEB, "src", "generated", "pysources.ts");

/** `dir` must be a directory; exit saying which one is missing if it is not.
 *
 * This script reads two trees that live outside `web/`, so it runs fine from the wrong
 * working directory or against a half-checked-out tree and then writes an empty table -
 * and the app boots, loads no `bench` at all, and fails in Python with an import error
 * about a module nobody can find. Saying so here is the whole difference.
 */
async function directory(dir, what) {
  const info = await stat(dir).catch(() => null);
  if (info !== null && info.isDirectory()) return;
  console.error(
    `bundle-py: ${what} is not at ${dir}` +
      " - run this from the repository's web/ directory, in a full checkout",
  );
  process.exit(1);
}

await directory(join(PY_ROOT, "bench"), "the bench package");
await directory(EXAMPLES, "the examples");
await directory(dirname(STARTER), "the templates");

/** Every *.py under `dir`, depth first, skipping caches. */
async function walk(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name === "__pycache__" || entry.name.startsWith(".")) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await walk(path)));
    else if (entry.name.endsWith(".py")) found.push(path);
  }
  return found.sort();
}

const key = (path, base) => relative(base, path).split(sep).join("/");

/** The latest mtime, in milliseconds, among `paths` - `0` for an empty list, so a tree with
 * nothing in it never claims to be newer than one that does. This is the same number
 * `bench:staleness` in `vite.config.ts` asks the running server to recompute live, so the
 * two can be compared without either side reading the other's clock. */
async function newest(paths) {
  let found = 0;
  for (const path of paths) {
    const info = await stat(path);
    found = Math.max(found, info.mtimeMs);
  }
  return found;
}

const benchPaths = await walk(join(PY_ROOT, "bench"));
const examplePaths = await walk(EXAMPLES);
const generatedAt = Math.max(await newest(benchPaths), await newest(examplePaths));

const sources = {};
for (const path of benchPaths) {
  sources[key(path, PY_ROOT)] = await readFile(path, "utf8");
}

const examples = {};
for (const path of examplePaths) {
  examples[key(path, EXAMPLES)] = await readFile(path, "utf8");
}

const table = (entries) =>
  Object.entries(entries)
    .map(([name, text]) => `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`)
    .join("\n");

const text = `// Generated by scripts/bundle-py.mjs - do not edit.
/** Every module of the Python side, keyed by its path relative to \`src/\`. */
export const PY_SOURCES: Record<string, string> = {
${table(sources)}
};

/** The bundled example scripts, keyed by filename. */
export const EXAMPLES: Record<string, string> = {
${table(examples)}
};

/** What a new file starts as: \`templates/untitled.py\`. */
export const STARTER: string = ${JSON.stringify(await readFile(STARTER, "utf8"))};

/** The latest mtime, in milliseconds, among the Python this bundle was built from - what
 * \`bench:staleness\` in \`vite.config.ts\` compares against the same trees' live mtime to
 * say whether this bundle is older than what is on disk right now. */
export const GENERATED_AT: number = ${JSON.stringify(generatedAt)};
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, text, "utf8");
console.log(
  `bundle-py: ${Object.keys(sources).length} modules, ${Object.keys(examples).length} examples` +
    ` -> ${relative(WEB, OUT)}`,
);
